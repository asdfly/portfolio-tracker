def ymd(s):
    """YYYYMMDD -> YYYY-MM-DD"""
    return f"{s[0:4]}-{s[4:6]}-{s[6:8]}"


def main():
    os.makedirs(DATA_DIR, exist_ok=True)
    written = 0
    for code, (market, setcode) in TARGETS.items():
        rows_raw = RAW[code]
        rows = []
        for (d, o, h, l, c, v, a) in rows_raw:
            # 结构校验：7 字段齐全、数值有限、日期合法
            for name, val in (("open", o), ("high", h), ("low", l), ("close", c),
                              ("volume", v), ("amount", a)):
                fv = float(val)
                if not __import__("math").isfinite(fv):
                    raise ValueError(f"{code} {d} {name} 非有限值: {val}")
            if int(d[0:4]) < 2000 or int(d[4:6]) > 12 or int(d[6:8]) > 31:
                raise ValueError(f"{code} 非法日期: {d}")
            rows.append({
                "date": ymd(d), "open": float(o), "high": float(h),
                "low": float(l), "close": float(c),
                "volume": float(v), "amount": float(a),
            })
        payload = {
            "source": "tdx",
            "code": code,
            "market": market,
            "setcode": setcode,
            "tqFlag": "1",
            "fetched_at": FETCHED_AT,
            "rows": rows,
        }
        out = os.path.join(DATA_DIR, f"etf_tdx_{code}_latest.json")
        with open(out, "w", encoding="utf-8") as fh:
            json.dump(payload, fh, ensure_ascii=False, indent=2)
        print(f"[OK] {code}: 写 {len(rows)} 行 "
              f"({rows[0]['date']}~{rows[-1]['date']}) -> {os.path.basename(out)}")
        written += 1
    print(f"\n[DONE] 共写 {written} 个 tdx 缓存文件")
    return written


if __name__ == "__main__":
    sys.exit(0 if main() == len(TARGETS) else 1)
